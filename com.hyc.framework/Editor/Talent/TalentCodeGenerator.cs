// 说明: 一键把配置好的天赋树生成为「运行期逻辑代码 + UI prefab」。
//       · <前缀>TalentController.cs  —— 逻辑代码(既是 TalentRuntime 又是 ITalentResourceProvider,
//                                       你只在 #region USER 里接"点数从哪来")。
//       · <前缀>TalentUI.cs          —— UI 代码(TalentTreeUIBase 子类, 在 ApplySlot 里画状态)。
//       · <前缀>TalentTree.prefab    —— 挂好基类组件、slots 已按节点预填的 prefab(口子)。
//       重生成的 #region GENERATED 块会被覆盖, #region USER 块原样保留。
// ============================================================

using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using HYC.Framework.Talent;
using UnityEditor;
using UnityEngine;

namespace HYC.Framework.Talent.Editor
{
    public static class TalentCodeGenerator
    {
        /// <summary>
        /// 生成天赋树的运行期代码与 prefab。
        /// </summary>
        /// <param name="asset">已配置好的天赋树资产。</param>
        /// <param name="onlyIds">非 null 且非空 = 只暴露这些节点; 否则暴露全部节点。</param>
        /// <param name="folder">输出目录(游戏工程内, 默认 Assets/Talent/Generated)。</param>
        /// <param name="prefix">类名前缀(会做 C# 标识符清洗)。</param>
        /// <param name="ns">生成代码的命名空间。</param>
        /// <returns>null = 成功; 否则返回错误信息。</returns>
        public static string Generate(TalentTreeAsset asset, List<int> onlyIds, string folder, string prefix, string ns)
        {
            if (asset == null) return "天赋树资产为空。";
            if (string.IsNullOrEmpty(folder)) return "输出目录不能为空。";

            var errs = TalentTreeValidator.Validate(asset).FindAll(i => i.IsError);
            if (errs.Count > 0)
                return "天赋树有错误, 先修正:\n" + string.Join("\n", errs.ConvertAll(i => i.Message));

            prefix = SanitizePrefix(prefix);
            if (string.IsNullOrEmpty(prefix)) return "类名前缀清洗后为空, 请换一个。";

            var tree = TalentTree.Build(asset);
            var chosen = new List<TalentNode>();
            if (onlyIds != null && onlyIds.Count > 0)
            {
                foreach (var id in onlyIds)
                {
                    var n = tree.GetNode(id);
                    if (n != null) chosen.Add(n);
                }
            }
            else
            {
                foreach (var n in tree.Nodes)
                    if (n != null) chosen.Add(n);
            }

            if (!Directory.Exists(folder)) Directory.CreateDirectory(folder);

            File.WriteAllText(Path.Combine(folder, prefix + "TalentController.cs"),
                BuildController(asset, prefix, ns), Encoding.UTF8);
            File.WriteAllText(Path.Combine(folder, prefix + "TalentUI.cs"),
                BuildUI(asset, prefix, ns), Encoding.UTF8);

            BuildPrefab(asset, prefix, folder, chosen);

            AssetDatabase.Refresh();
            return null; // 成功
        }

        // ------------------------------------------------------------
        //  产物 1: <前缀>TalentController.cs
        // ------------------------------------------------------------
        private static string BuildController(TalentTreeAsset asset, string prefix, string ns)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// ============================================================");
            sb.AppendLine("//  GENERATED by HYC Framework · Talent Tree Editor");
            sb.AppendLine("//  Tree : " + (string.IsNullOrEmpty(asset.displayName) ? asset.name : asset.displayName) + "  (treeId " + asset.treeId + ")");
            sb.AppendLine("//  ⚠ 只改 \"#region USER\" 里的内容; 重跑生成器会覆盖 \"#region GENERATED\" 块。");
            sb.AppendLine("// ============================================================");
            sb.AppendLine("using HYC.Framework.Talent;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine();
            sb.AppendLine("namespace " + ns);
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>" + (asset.displayName ?? asset.name) + " 的天赋控制器: 既是运行期状态机(TalentRuntime), 又实现资源提供器(ITalentResourceProvider)。</summary>");
            sb.AppendLine("    public class " + prefix + "TalentController : TalentRuntime, ITalentResourceProvider");
            sb.AppendLine("    {");
            sb.AppendLine("        #region GENERATED");
            sb.AppendLine("        public const long TreeId = " + asset.treeId + "L;");
            sb.AppendLine("        #endregion");
            sb.AppendLine();
            sb.AppendLine("        #region USER");
            sb.AppendLine("        // 构造函数: 把资源提供器指向自己(本类同时实现 ITalentResourceProvider)。");
            sb.AppendLine("        public " + prefix + "TalentController() { Resources = this; }");
            sb.AppendLine();
            sb.AppendLine("        // 这里把\"点数\"接到框架: attrKey 来自天赋树的\"黑板\", 真正数值由它指向的配置行决定。");
            sb.AppendLine("        // 框架不认识\"力量/金币\", 只认 key —— 你按 key 去自己的存档/角色属性里查、扣。");
            sb.AppendLine("        public int GetAvailable(string attrKey)");
            sb.AppendLine("        {");
            sb.AppendLine("            // TODO: 返回 attrKey 当前可用点数");
            sb.AppendLine("            return 0;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public bool Consume(string attrKey, int amount)");
            sb.AppendLine("        {");
            sb.AppendLine("            // TODO: 从 attrKey 对应的池子里扣 amount, 成功返回 true");
            sb.AppendLine("            return false;");
            sb.AppendLine("        }");
            sb.AppendLine("        #endregion");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // ------------------------------------------------------------
        //  产物 2: <前缀>TalentUI.cs
        // ------------------------------------------------------------
        private static string BuildUI(TalentTreeAsset asset, string prefix, string ns)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// ============================================================");
            sb.AppendLine("//  GENERATED by HYC Framework · Talent Tree Editor");
            sb.AppendLine("//  Tree : " + (string.IsNullOrEmpty(asset.displayName) ? asset.name : asset.displayName));
            sb.AppendLine("//  ⚠ 只改 \"#region USER\" 里的内容; 重跑生成器会覆盖 \"#region GENERATED\" 块。");
            sb.AppendLine("// ============================================================");
            sb.AppendLine("using HYC.Framework.Talent;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine();
            sb.AppendLine("namespace " + ns);
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>" + (asset.displayName ?? asset.name) + " 的天赋 UI(子类): 在 ApplySlot 里按状态画颜色/文本/特效。</summary>");
            sb.AppendLine("    public class " + prefix + "TalentUI : TalentTreeUIBase");
            sb.AppendLine("    {");
            sb.AppendLine("        #region GENERATED");
            sb.AppendLine("        // slots 已由生成器预填(每个节点一个槽位)。可在 Inspector 里拖拽增删/重排。");
            sb.AppendLine("        #endregion");
            sb.AppendLine();
            sb.AppendLine("        #region USER");
            sb.AppendLine("        // protected override void ApplySlot(TalentNodeSlot slot, TalentNode node, SlotState state)");
            sb.AppendLine("        // {");
            sb.AppendLine("        //     var go = slot.node != null ? transform.Find(node.title) : null;");
            sb.AppendLine("        //     var btn = go != null ? go.GetComponent<UnityEngine.UI.Button>() : null;");
            sb.AppendLine("        //     if (btn != null) btn.interactable = state == SlotState.Available;");
            sb.AppendLine("        //     // Locked = 灰, Available = 绿, Unlocked = 金");
            sb.AppendLine("        // }");
            sb.AppendLine("        #endregion");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // ------------------------------------------------------------
        //  产物 3: <前缀>TalentTree.prefab (基类组件 + slots 预填)
        // ------------------------------------------------------------
        private static void BuildPrefab(TalentTreeAsset asset, string prefix, string folder, List<TalentNode> nodes)
        {
            var go = new GameObject(prefix + "TalentTree");
            var comp = go.AddComponent<TalentTreeUIBase>();

            // 用 SerializedObject 填字段, 不依赖具体子类是否编译
            var so = new SerializedObject(comp);
            so.Update();
            so.FindProperty("treeAsset").objectReferenceValue = asset;
            var slots = so.FindProperty("slots");
            slots.arraySize = nodes.Count;
            for (int i = 0; i < nodes.Count; i++)
            {
                var elem = slots.GetArrayElementAtIndex(i);
                elem.FindPropertyRelative("node").objectReferenceValue = nodes[i];
            }
            so.ApplyModifiedProperties();

            var prefabPath = AssetDatabase.GenerateUniqueAssetPath(Path.Combine(folder, prefix + "TalentTree.prefab"));
            PrefabUtility.SaveAsPrefabAsset(go, prefabPath);
            UnityEngine.Object.DestroyImmediate(go);
            AssetDatabase.SaveAssets();
        }

        /// <summary>把任意字符串洗成合法的 C# 类型名前缀(首字符为字母, 其余字母/数字/下划线)。</summary>
        public static string SanitizePrefix(string raw)
        {
            if (string.IsNullOrEmpty(raw)) return "";
            var sb = new StringBuilder();
            foreach (var c in raw)
            {
                if (char.IsLetterOrDigit(c) || c == '_')
                    sb.Append(c);
                else if (c == ' ' || c == '-' || c == '/' || c == '\\' || c == '.')
                    sb.Append('_');
            }
            var s = sb.ToString().Trim('_');
            if (s.Length == 0) return "";
            // 首字符必须是字母或下划线
            if (!char.IsLetter(s[0]) && s[0] != '_')
                s = "_" + s;
            return s;
        }
    }
}

using System;
using System.IO;
using HYC.Framework.Editor;
using NUnit.Framework;

namespace HYC.Framework.Tests
{
    /// <summary>
    /// <see cref="GeneratedCodeFile"/>（生成代码统一写盘最底层）的契约。
    ///
    /// <para><b>为什么这个契约要紧</b>：包内所有代码生成器都走这里写 .cs，两个不变量必须钉住——
    /// ① 每个产出文件顶部套「自动生成」壳（禁手工改声明），缺壳被人手改后下次生成静默覆盖，事故典型；
    /// ② 壳内不含时间戳等易变信息，否则每次生成内容都不同、「内容未变不重写」优化失效，白触发重编译。</para>
    ///
    /// <para><b>注意</b>：这些用例会在工程内创建临时文件，位于 <c>Temp/</c> 下，TearDown 会清理。
    /// 只测纯函数与写盘比对，不调 <c>AssetDatabase.ImportAsset</c>（会触发导入与编译抖动）。</para>
    /// </summary>
    public class GeneratedCodeFileTests
    {
        private const string TempDir = "Temp/GeneratedCodeFileTests";
        private string _dirAbs;

        [SetUp]
        public void SetUp()
        {
            _dirAbs = Path.Combine(Directory.GetCurrentDirectory(), TempDir);
            if (Directory.Exists(_dirAbs)) Directory.Delete(_dirAbs, true);
            Directory.CreateDirectory(_dirAbs);
        }

        [TearDown]
        public void TearDown()
        {
            try
            {
                if (Directory.Exists(_dirAbs)) Directory.Delete(_dirAbs, true);
            }
            catch (IOException)
            {
                // 文件被占用等；临时目录残留不致命，不让测试因此失败
            }
        }

        private string Rel(string name) => TempDir + "/" + name;

        [Test]
        public void 头壳_含自动生成标签与禁改声明()
        {
            Assert.IsTrue(GeneratedCodeFile.Header.Contains("// <auto-generated>"),
                "壳首行必须是 IDE 识别的 <auto-generated> 标签");
            Assert.IsTrue(GeneratedCodeFile.Header.Contains("请勿手工修改"),
                "壳必须含中文禁改声明");
            Assert.IsTrue(GeneratedCodeFile.Header.Contains("DO NOT EDIT"),
                "壳必须含英文禁改声明（包是公开仓库）");
            Assert.IsTrue(GeneratedCodeFile.Header.EndsWith("\n") || GeneratedCodeFile.Header.EndsWith("\r\n"),
                "壳以换行结尾，保证原内容从新的一行开始");
        }

        [Test]
        public void 头壳_不含时间戳等易变信息()
        {
            // 壳里一旦混入时间戳/绝对路径，"内容未变不重写" 会失效——每次生成都判为变化、白写白编译。
            Assert.IsFalse(GeneratedCodeFile.Header.Contains(DateTime.Now.Year.ToString()),
                "壳不得含当前年份（防有人加时间戳）");
            Assert.IsFalse(GeneratedCodeFile.Header.Contains(Directory.GetCurrentDirectory()),
                "壳不得含工程绝对路径");
        }

        [Test]
        public void WithHeader_头在前_原内容整体后移()
        {
            const string code = "using System;\nnamespace X { }";
            var result = GeneratedCodeFile.WithHeader(code);

            Assert.IsTrue(result.StartsWith(GeneratedCodeFile.Header), "头必须在最前");
            Assert.IsTrue(result.EndsWith(code), "原内容必须整体保留在头之后");
            Assert.AreEqual(GeneratedCodeFile.Header + code, result, "WithHeader 就是简单的头 + 原内容");
        }

        [Test]
        public void WriteIfChanged_套壳内容_首次写_重复跳过()
        {
            var path = Rel("Banner.cs");
            var content = GeneratedCodeFile.WithHeader("// body\n");

            Assert.IsTrue(GeneratedCodeFile.WriteIfChanged(path, content), "首次应写");
            Assert.AreEqual(content, File.ReadAllText(Path.Combine(_dirAbs, "Banner.cs")),
                "落盘内容 = 壳 + 原内容");

            Assert.IsFalse(GeneratedCodeFile.WriteIfChanged(path, content),
                "重复写相同套壳内容应跳过（壳稳定才有此性质）");
        }
    }
}

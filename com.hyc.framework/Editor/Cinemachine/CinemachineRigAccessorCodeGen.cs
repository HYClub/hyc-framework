// ============================================================
// HYC Framework - Cinemachine 相机装配 · 机位访问器代码生成
// 文件: Editor/Cinemachine/CinemachineRigAccessorCodeGen.cs
// 说明: 为每个 rig prefab 生成一个静态访问器类，让宿主代码拿机位
//       不用手打节点名字符串（改名后重新生成即可，不会静默指错）。
//       落点 GeneratedPaths.Cinemachine，命名空间 {root}.Cinemachine。
//       触发时机：窗口保存 rig / 新建 rig / 打开 rig 时（内容未变不重写）。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using HYC.Framework.Editor;
using Unity.Cinemachine;
using UnityEditor;
using UnityEngine;

namespace HYC.Framework.Cinemachine.Editor
{
    /// <summary>
    /// 机位访问器生成器。生成物形如：
    /// <code>
    /// public static class PlayerRigCameras
    /// {
    ///     public static CinemachineCamera FreeLook(CinemachineRigBinder rig) => ...;
    ///     public static bool ToFreeLook(CinemachineRigBinder rig) => ...;
    /// }
    /// </code>
    /// <para>类名 = prefab 文件名 + <c>Cameras</c>；不同目录同名 prefab 会自动加目录名/短 GUID 区分。</para>
    /// </summary>
    internal static class CinemachineRigAccessorCodeGen
    {
        private const string FileSuffix = ".g.cs";
        private const string SourceHeader = "// source: ";
        private const string ClassHeader = "// class: ";
        private const string AccessorSuffix = "Cameras";
        private const string NodePrefix = "vcam_";

        private readonly struct CameraEntry
        {
            public readonly string NodeName;
            public readonly RigKind Kind;
            public readonly string RecipeName;

            public CameraEntry(string nodeName, RigKind kind, string recipeName)
            {
                NodeName = nodeName;
                Kind = kind;
                RecipeName = recipeName;
            }
        }

        /// <summary>按已加载的 rig 内容生成（窗口保存后调用，避免二次加载 prefab）。</summary>
        public static void Generate(GameObject rigRoot, string prefabPath)
        {
            if (rigRoot == null || string.IsNullOrEmpty(prefabPath))
                return;

            DeleteStaleFiles();

            var taken = ScanExistingClasses();
            var className = ResolveClassName(prefabPath, taken);
            var entries = CollectCameras(rigRoot);
            WriteFile(prefabPath, className, entries);
        }

        /// <summary>从 prefab 资产加载后生成（新建 rig 等没有内存实例的场景用）。</summary>
        public static void GenerateFromAsset(string prefabPath)
        {
            if (string.IsNullOrEmpty(prefabPath))
                return;

            var root = PrefabUtility.LoadPrefabContents(prefabPath);
            if (root == null)
            {
                Debug.LogWarning("[HYC.Cinemachine] 无法加载 rig prefab 以生成访问器：" + prefabPath);
                return;
            }

            try
            {
                Generate(root, prefabPath);
            }
            finally
            {
                PrefabUtility.UnloadPrefabContents(root);
            }
        }

        // ---------- 采集 ----------

        private static List<CameraEntry> CollectCameras(GameObject rigRoot)
        {
            var list = new List<CameraEntry>();
            for (int i = 0; i < rigRoot.transform.childCount; i++)
            {
                var child = rigRoot.transform.GetChild(i);
                if (child == null || child.GetComponent<CinemachineCamera>() == null)
                    continue;

                var tag = child.GetComponent<CinemachineRigCameraTag>();
                var kind = tag != null ? tag.Kind : RigKind.ThirdPerson;
                list.Add(new CameraEntry(child.name, kind, RigKinds.Get(kind).DisplayName));
            }
            return list;
        }

        private static string BuildText(string prefabPath, string className, List<CameraEntry> cameras)
        {
            var rigName = Path.GetFileNameWithoutExtension(prefabPath);
            var sb = new StringBuilder(1024);

            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//   由 HYC Framework 相机装配窗口生成，请勿手改（重新生成会覆盖）。");
            sb.AppendLine("//   改了 rig 结构后：在 Rig Editor 里点 Save，或重新打开该 rig。");
            sb.AppendLine("//   宿主程序集需引用 HYC.Framework.Runtime 与 Unity.Cinemachine。");
            sb.AppendLine(SourceHeader + prefabPath);
            sb.AppendLine(ClassHeader + className);
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("using Unity.Cinemachine;");
            sb.AppendLine("using HYC.Framework.Cinemachine;");
            sb.AppendLine();
            sb.AppendLine("namespace " + HYCSettings.CinemachineCodeNamespace);
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>" + EscapeXml(rigName) + " 的机位访问器（"
                          + cameras.Count + " 个机位，随 rig prefab 生成）。</summary>");
            sb.AppendLine("    public static class " + className);
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>机位数量。</summary>");
            sb.AppendLine("        public const int Count = " + cameras.Count + ";");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>全部机位节点名（顺序 = prefab 子节点顺序）。</summary>");
            sb.AppendLine("        public static readonly string[] Names =");
            sb.AppendLine("        {");
            for (int i = 0; i < cameras.Count; i++)
                sb.AppendLine("            \"" + EscapeLiteral(cameras[i].NodeName) + "\",");
            sb.AppendLine("        };");

            // 预留固定成员名与类名：机位恰好叫 Count/Names/类名时不至于吐重复声明
            var used = new HashSet<string>(StringComparer.Ordinal) { "Count", "Names", className };
            for (int i = 0; i < cameras.Count; i++)
            {
                var entry = cameras[i];
                var id = UniqueIdentifier(entry.NodeName, i, used);
                var literal = EscapeLiteral(entry.NodeName);
                var summary = "「" + EscapeXml(entry.NodeName) + "」机位（" + EscapeXml(entry.RecipeName) + "）";

                sb.AppendLine();
                sb.AppendLine("        /// <summary>取" + summary + "；不存在返 null。</summary>");
                sb.AppendLine("        public static CinemachineCamera " + id
                              + "(CinemachineRigBinder rig) => rig != null ? rig.Get(\"" + literal + "\") : null;");
                sb.AppendLine();
                sb.AppendLine("        /// <summary>切到" + summary + "；不存在返 false。</summary>");
                sb.AppendLine("        public static bool To" + id
                              + "(CinemachineRigBinder rig) => rig != null && rig.SwitchTo(\"" + literal + "\");");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        // ---------- 命名 ----------

        private static string UniqueIdentifier(string nodeName, int index, HashSet<string> used)
        {
            var id = ToIdentifier(nodeName);
            if (id.Length == 0)
                id = "Camera" + index;
            var candidate = id;
            var suffix = 2;
            while (!used.Add(candidate))
            {
                candidate = id + suffix;
                suffix++;
            }
            return candidate;
        }

        private static string ToIdentifier(string nodeName)
        {
            var name = nodeName ?? string.Empty;
            if (name.StartsWith(NodePrefix, StringComparison.OrdinalIgnoreCase))
                name = name.Substring(NodePrefix.Length);

            var raw = SanitizeName(name);
            if (raw.Length == 0)
                return string.Empty;

            // 首字母大写，产出 FreeLook 这种像类型成员的写法
            return char.ToUpperInvariant(raw[0]) + raw.Substring(1);
        }

        private static string SanitizeName(string raw)
        {
            if (string.IsNullOrEmpty(raw))
                return string.Empty;

            var sb = new StringBuilder(raw.Length);
            for (int i = 0; i < raw.Length; i++)
            {
                var c = raw[i];
                if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
                    || (c >= '0' && c <= '9') || c == '_')
                {
                    sb.Append(c);
                }
            }

            var result = sb.ToString();
            if (result.Length == 0)
                return string.Empty;
            if (result[0] >= '0' && result[0] <= '9')
                result = "Rig" + result;
            return result;
        }

        private static string ResolveClassName(string prefabPath, Dictionary<string, string> taken)
        {
            var stem = SanitizeName(Path.GetFileNameWithoutExtension(prefabPath));
            if (stem.Length == 0)
                stem = "Rig";

            var candidate = stem + AccessorSuffix;
            if (!Conflicts(candidate, prefabPath, taken))
                return candidate;

            var folder = SanitizeName(ParentFolderName(prefabPath));
            if (folder.Length > 0)
            {
                candidate = stem + folder + AccessorSuffix;
                if (!Conflicts(candidate, prefabPath, taken))
                    return candidate;
            }

            var guid = AssetDatabase.AssetPathToGUID(prefabPath);
            var tail = guid.Length >= 6 ? guid.Substring(0, 6) : guid;
            return stem + folder + "_" + tail + AccessorSuffix;
        }

        private static bool Conflicts(string className, string prefabPath, Dictionary<string, string> taken)
        {
            return taken.TryGetValue(className, out var source)
                   && !string.Equals(source, prefabPath, StringComparison.Ordinal);
        }

        private static string ParentFolderName(string assetPath)
        {
            var dir = Path.GetDirectoryName(assetPath.Replace('\\', '/')) ?? string.Empty;
            var parts = dir.Split('/');
            return parts.Length > 0 ? parts[parts.Length - 1] : string.Empty;
        }

        // ---------- 落盘 ----------

        private static void WriteFile(string prefabPath, string className, List<CameraEntry> cameras)
        {
            var dir = GeneratedPaths.Cinemachine;
            if (!AssetDatabase.IsValidFolder(dir))
            {
                Directory.CreateDirectory(dir);
                AssetDatabase.Refresh();
            }

            var targetPath = dir + "/" + className + FileSuffix;
            var text = BuildText(prefabPath, className, cameras);
            var fullPath = Path.GetFullPath(targetPath);

            DeleteOtherFilesOfSource(prefabPath, targetPath);

            try
            {
                if (File.Exists(fullPath) && File.ReadAllText(fullPath) == text)
                    return;

                File.WriteAllText(fullPath, text, new UTF8Encoding(false));
                AssetDatabase.ImportAsset(targetPath, ImportAssetOptions.ForceUpdate);
            }
            catch (IOException e)
            {
                Debug.LogError("[HYC.Cinemachine] 生成机位访问器失败 " + targetPath + "：" + e.Message);
            }
            catch (UnauthorizedAccessException e)
            {
                Debug.LogError("[HYC.Cinemachine] 生成机位访问器无写权限 " + targetPath + "：" + e.Message);
            }
        }

        /// <summary>prefab 改名或类名规则变化后，同源旧文件会被遗弃，这里清掉。</summary>
        private static void DeleteOtherFilesOfSource(string prefabPath, string keepPath)
        {
            foreach (var path in EnumerateGeneratedFiles())
            {
                if (string.Equals(path, keepPath, StringComparison.Ordinal))
                    continue;
                if (string.Equals(ReadHeader(path, SourceHeader), prefabPath, StringComparison.Ordinal))
                    AssetDatabase.DeleteAsset(path);
            }
        }

        /// <summary>源 prefab 已删 / 已移走的生成文件，在每次生成时顺手清掉。</summary>
        private static void DeleteStaleFiles()
        {
            foreach (var path in EnumerateGeneratedFiles())
            {
                var source = ReadHeader(path, SourceHeader);
                if (string.IsNullOrEmpty(source))
                    continue;
                if (AssetDatabase.LoadAssetAtPath<GameObject>(source) == null)
                    AssetDatabase.DeleteAsset(path);
            }
        }

        private static List<string> EnumerateGeneratedFiles()
        {
            var list = new List<string>();
            var dir = GeneratedPaths.Cinemachine;
            if (!AssetDatabase.IsValidFolder(dir))
                return list;

            var guids = AssetDatabase.FindAssets(string.Empty, new[] { dir });
            for (int i = 0; i < guids.Length; i++)
            {
                var path = AssetDatabase.GUIDToAssetPath(guids[i]);
                if (path.EndsWith(FileSuffix, StringComparison.Ordinal))
                    list.Add(path);
            }
            return list;
        }

        private static Dictionary<string, string> ScanExistingClasses()
        {
            var map = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var path in EnumerateGeneratedFiles())
            {
                var className = ReadHeader(path, ClassHeader);
                var source = ReadHeader(path, SourceHeader);
                if (!string.IsNullOrEmpty(className) && !string.IsNullOrEmpty(source))
                    map[className] = source;
            }
            return map;
        }

        /// <summary>读生成文件头部的元信息行（<c>// class: X</c> / <c>// source: Y</c>）。</summary>
        private static string ReadHeader(string assetPath, string prefix)
        {
            try
            {
                var lines = File.ReadAllLines(Path.GetFullPath(assetPath));
                for (int i = 0; i < lines.Length && i < 12; i++)
                {
                    if (lines[i].StartsWith(prefix, StringComparison.Ordinal))
                        return lines[i].Substring(prefix.Length).Trim();
                }
            }
            catch (IOException e)
            {
                Debug.LogWarning("[HYC.Cinemachine] 读取生成文件失败 " + assetPath + "：" + e.Message);
            }
            return null;
        }

        // ---------- 文本转义 ----------

        private static string EscapeLiteral(string value)
        {
            return (value ?? string.Empty).Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        private static string EscapeXml(string value)
        {
            return (value ?? string.Empty).Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        }
    }
}
